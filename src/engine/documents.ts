export function documentTotal(doc: SimDocument): number {
  return doc.lines.reduce((s, l) => s + l.amount, 0)
}

export function documentVat(doc: SimDocument): number {
  return doc.lines.reduce((s, l) => s + (l.vat ?? 0), 0)
}
